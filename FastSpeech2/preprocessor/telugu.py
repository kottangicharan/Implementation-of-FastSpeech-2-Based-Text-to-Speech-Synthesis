import os

from text import telugu
from preprocessor.hf_corpus import export


def prepare_align(config):
    sel = config["preprocessing"]["selection"]

    def get_speaker(item):
        # One speaker per gender in IndicTTS Telugu (0 = female, 1 = male)
        return "female" if item["gender"] in (0, "0", "female") else "male"

    def get_text(item):
        return " ".join(telugu.words(telugu.normalize_telugu(item["text"])))

    # Balance the two speakers: neither female (4.27h) nor male (4.47h) alone reaches 6h
    selected = export(config, get_speaker, get_text, per_speaker_cap=sel["total_hours"] / 2 + 0.5)

    # Pronunciation dictionary for MFA, generated by the rule-based G2P
    vocab = set()
    raw = config["path"]["raw_path"]
    for speaker, basename, _ in selected:
        with open(os.path.join(raw, speaker, basename + ".lab"), encoding="utf-8") as f:
            vocab.update(f.read().split())
    lex_path = config["path"]["lexicon_path"]
    os.makedirs(os.path.dirname(lex_path), exist_ok=True)
    with open(lex_path, "w", encoding="utf-8") as f:
        for w in sorted(vocab):
            p = telugu.word_to_phones(w)
            if p:
                f.write("{}\t{}\n".format(w, " ".join(p)))
    print("Lexicon: {} words -> {}".format(len(vocab), lex_path))
